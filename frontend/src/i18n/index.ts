const activeLocale = ref<AppLocale>(DEFAULT_LOCALE)

export function normalizeLocale(value: unknown): AppLocale {
  return value === 'en-US' ? 'en-US' : DEFAULT_LOCALE
}

export function setActiveLocale(value: AppLocale): void {
  const locale = normalizeLocale(value)
  activeLocale.value = locale
  document.documentElement.lang = locale
  document.documentElement.dir = 'ltr'
}

export function getActiveLocale(): AppLocale {
  return activeLocale.value
}

export function translateForLocale(locale: AppLocale, key: string, values: Record<string, string | number> = {}): string {
  const template = messages[normalizeLocale(locale)][key] ?? messages[DEFAULT_LOCALE][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}

export function t(key: string, values?: Record<string, string | number>): string {
  return translateForLocale(activeLocale.value, key, values)
}

export function formatDate(value: Date | number, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(activeLocale.value, options).format(value)
}

export function formatNumber(value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(activeLocale.value, options).format(value)
}

export function useI18n() {
  return { locale: readonly(activeLocale), t, formatDate, formatNumber }
}

export function messageKeys(locale: AppLocale): string[] {
  return Object.keys(messages[locale]).sort()
}
